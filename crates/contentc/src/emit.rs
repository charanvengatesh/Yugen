fn str_lit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn f32_lit(v: f64) -> String {
    let f = v as f32;
    if f.is_infinite() {
        return if f > 0.0 {
            "f32::INFINITY".into()
        } else {
            "f32::NEG_INFINITY".into()
        };
    }
    if f.is_nan() {
        return "f32::NAN".into();
    }
    // Debug for floats is the shortest round-tripping form and always carries a
    // `.` or an exponent, so it is a valid float literal on its own.
    format!("{f:?}")
}

/// One table slot. Integer arrays reject a value that would not survive the
/// store, rather than wrapping the way a JS typed array silently would.
fn table_lit(kind: ArrayKind, v: f64, table: &str, code: usize) -> Result<String> {
    if kind == ArrayKind::F32 {
        return Ok(f32_lit(v));
    }
    let max = match kind {
        ArrayKind::U8 => 255.0,
        ArrayKind::U16 => 65535.0,
        ArrayKind::U32 => 4294967295.0,
        ArrayKind::F32 => unreachable!(),
    };
    if !v.is_finite() || v.fract() != 0.0 || v < 0.0 || v > max {
        bail!(
            "{table}[{code}] = {v} does not fit a {} — a table's array kind and its \
             callback disagree",
            kind.rust_elem()
        );
    }
    Ok(format!("{}", v as u64))
}

fn value_lit(node: &TypeNode, field: &Field, scope: &str, key: &str, v: &Value) -> Result<String> {
    Ok(match (node, v) {
        (TypeNode::Enum(_), Value::Int(n)) => format!("{n}"),
        (TypeNode::Enum(_), Value::Str(s)) => {
            format!("{}::{}", enum_name(scope, key, field), names::pascal(s))
        }
        (TypeNode::Int, Value::Int(n)) => format!("{n}"),
        (TypeNode::Int, Value::Float(f)) => format!("{}", *f as i64),
        (TypeNode::Float | TypeNode::Chance, v) => {
            f32_lit(v.as_num().ok_or_else(|| err!("'{key}' is not numeric"))?)
        }
        (TypeNode::Bool, Value::Bool(b)) => format!("{b}"),
        (TypeNode::Str | TypeNode::Ref { .. }, Value::Str(s)) => str_lit(s),
        (TypeNode::Color, Value::Color(c)) => format!("[{}, {}, {}]", c[0], c[1], c[2]),
        (TypeNode::Range, Value::Range(a, b)) => format!("[{}, {}]", f32_lit(*a), f32_lit(*b)),
        (TypeNode::Text, Value::Text(lines)) => {
            let parts: Vec<String> = lines.iter().map(|l| str_lit(l)).collect();
            format!("&[{}]", parts.join(", "))
        }
        (TypeNode::List(of), Value::List(items)) => {
            let mut parts = Vec::with_capacity(items.len());
            for it in items {
                parts.push(value_lit(of, field, scope, key, it)?);
            }
            format!("&[{}]", parts.join(", "))
        }
        (TypeNode::Record, Value::Records(rows)) => {
            let elem = field
                .element
                .clone()
                .ok_or_else(|| err!("'{key}' is record[] but names no element struct"))?;
            let subs = field
                .fields
                .as_ref()
                .ok_or_else(|| err!("'{key}' is record[] but declares no fields"))?;
            let mut parts = Vec::with_capacity(rows.len());
            for row in rows {
                let mut inner = Vec::with_capacity(subs.len());
                for (sk, sf) in subs {
                    let snode = parse_type(&sf.ty)?;
                    let lit = match row.get(sk) {
                        Some(val) => {
                            let l = value_lit(&snode, sf, &elem, sk, val)?;
                            if is_optional(sf) {
                                format!("Some({l})")
                            } else {
                                l
                            }
                        }
                        None if is_optional(sf) => "None".to_string(),
                        None => bail!("'{key}.{sk}' has no value and is not optional"),
                    };
                    inner.push(format!("{}: {lit}", names::snake(sk)));
                }
                parts.push(format!("{elem} {{ {} }}", inner.join(", ")));
            }
            format!("&[{}]", parts.join(", "))
        }
        (n, v) => {
            bail!("'{key}': cannot render a {} as {n:?}", v.type_name())
        }
    })
}

