/// Wrap prose to a `///` doc comment at the given indent.
fn doc(text: Option<&String>, indent: &str) -> Vec<String> {
    let Some(text) = text else { return Vec::new() };
    if text.is_empty() {
        return Vec::new();
    }
    let mut lines: Vec<String> = Vec::new();
    let mut line = String::new();
    for w in text.split_whitespace() {
        if !line.is_empty() && line.len() + w.len() + 1 > 74 {
            lines.push(std::mem::take(&mut line));
            line.push_str(w);
        } else {
            if !line.is_empty() {
                line.push(' ');
            }
            line.push_str(w);
        }
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
        .into_iter()
        .map(|l| format!("{indent}/// {l}"))
        .collect()
}

/// Wrap a comma-separated list so diffs stay narrow.
fn wrap(items: &[String], indent: &str) -> String {
    let mut lines: Vec<String> = Vec::new();
    let mut line = indent.to_string();
    for (i, item) in items.iter().enumerate() {
        let piece = format!("{item}{}", if i == items.len() - 1 { "" } else { "," });
        if line.len() + piece.len() + 1 > 92 && line != indent {
            lines.push(std::mem::take(&mut line));
            line.push_str(indent);
        }
        if line != indent {
            line.push(' ');
        }
        line.push_str(&piece);
    }
    if line != indent {
        lines.push(line);
    }
    lines.join("\n")
}

/// One generated enum: its Rust name, its variants in order, and its doc.
type EnumDecl = (String, Vec<String>, Option<String>);

/// Every enum a schema needs declared, in declaration order, deduplicated.
fn collect_enums(schema: &Schema) -> Result<Vec<EnumDecl>> {
    let (flat, groups) = partition(schema);
    let mut out: Vec<EnumDecl> = Vec::new();
    let mut push = |name: String, values: Vec<String>, d: Option<String>| -> Result<()> {
        if let Some((_, existing, _)) = out.iter().find(|(n, _, _)| *n == name) {
            if *existing != values {
                bail!("two different enums are both named '{name}'");
            }
            return Ok(());
        }
        out.push((name, values, d));
        Ok(())
    };

    let walk = |scope: &str, key: &str, field: &Field| -> Result<Vec<EnumDecl>> {
        let mut found = Vec::new();
        let mut node = parse_type(&field.ty)?;
        while let TypeNode::List(of) = node {
            node = *of;
        }
        if let TypeNode::Enum(values) = node
            && field.map.is_none()
        {
            found.push((enum_name(scope, key, field), values, field.doc.clone()));
        }
        Ok(found)
    };

    let mut all: Vec<(&str, &str, &Field)> = Vec::new();
    for (k, f) in &flat {
        all.push((schema.iface_prefix.as_str(), k, f));
    }
    for (_, fields) in &groups {
        for (k, f) in fields {
            all.push((schema.iface_prefix.as_str(), k, f));
        }
    }

    for (scope, key, field) in &all {
        for e in walk(scope, key, field)? {
            push(e.0, e.1, e.2)?;
        }
        // `record[]` sub-fields carry enums too — `mode` and `state` on a sprite
        // sequence — and they are scoped to the element struct.
        if let (Some(elem), Some(subs)) = (&field.element, &field.fields) {
            for (sk, sf) in subs {
                for e in walk(elem, sk, sf)? {
                    push(e.0, e.1, e.2)?;
                }
            }
        }
    }
    Ok(out)
}

fn print(
    schema: &Schema,
    defs: &[Def],
    count: usize,
    tctx: &TableCtx,
    sources: &[String],
    tombstones: &[String],
) -> Result<String> {
    let (flat, groups) = partition(schema);
    let mut out: Vec<String> = Vec::new();
    let p = &schema.prefix;

    out.push(GEN_HEADER.to_string());
    out.push(format!(
        "// {count} {}s from {} source file(s):",
        schema.kind,
        sources.len()
    ));
    for s in sources {
        out.push(format!("//   {s}"));
    }
    if !tombstones.is_empty() {
        out.push(format!("// tombstoned: {}", tombstones.join(", ")));
    }
    out.push("//".to_string());
    out.push("// Edit content/ and run `cargo run -p contentc`. Schemas live in".to_string());
    out.push("// crates/contentc/src/schemas/.".to_string());
    out.push(String::new());
    out.push("#![allow(clippy::all)]".to_string());
    out.push(String::new());

    // --- named enums ---------------------------------------------------------
    let enums = collect_enums(schema)?;
    for (name, values, d) in &enums {
        out.extend(doc(d.as_ref(), ""));
        out.push("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]".to_string());
        out.push("#[repr(u8)]".to_string());
        out.push(format!("pub enum {name} {{"));
        for v in values {
            out.push(format!("    {},", names::pascal(v)));
        }
        out.push("}".to_string());
        out.push(String::new());
    }

    // --- element structs -----------------------------------------------------
    //
    // Grouped fields are walked too, not just flat ones: `art.seq` is a
    // `record[]` living under the `art` group, and the group struct below
    // renders it as `&[MobSpecSeq]`, so skipping groups here emits a module that
    // references a type it never declares. The dedupe is not theoretical — two
    // fields may legitimately share one element shape by naming the same
    // element, and a repeated `pub struct` is a hard error.
    let mut elements: Vec<&str> = Vec::new();
    let mut all_fields: Vec<(&str, &Field)> = flat.clone();
    for (_, fields) in &groups {
        all_fields.extend(fields.iter().copied());
    }
    for (_, field) in &all_fields {
        let (Some(elem), Some(subs)) = (&field.element, &field.fields) else {
            continue;
        };
        if elements.contains(&elem.as_str()) {
            continue;
        }
        elements.push(elem.as_str());
        out.push("#[derive(Clone, Copy, Debug, PartialEq)]".to_string());
        out.push(format!("pub struct {elem} {{"));
        for (sk, sf) in subs {
            out.extend(doc(sf.doc.as_ref(), "    "));
            let t = rust_type(elem, sk, sf)?;
            let t = if is_optional(sf) {
                format!("Option<{t}>")
            } else {
                t
            };
            out.push(format!("    pub {}: {t},", names::snake(sk)));
        }
        out.push("}".to_string());
        out.push(String::new());
    }

    // --- group structs -------------------------------------------------------
    for (name, fields) in &groups {
        out.push("#[derive(Clone, Copy, Debug, PartialEq)]".to_string());
        out.push(format!(
            "pub struct {}{} {{",
            schema.iface_prefix,
            names::pascal(name)
        ));
        for (k, sf) in fields {
            out.extend(doc(sf.doc.as_ref(), "    "));
            let t = rust_type(&schema.iface_prefix, k, sf)?;
            // A group's sub-field defaults are NOT injected when the group is
            // absent, so only `required` makes one non-optional.
            let t = if sf.required {
                t
            } else {
                format!("Option<{t}>")
            };
            out.push(format!("    pub {}: {t},", names::snake(k)));
        }
        out.push("}".to_string());
        out.push(String::new());
    }

    // --- the def struct ------------------------------------------------------
    out.extend(doc(
        Some(&format!(
            "The compiled shape of one {}. Derived from crates/contentc/src/schemas/.",
            schema.kind
        )),
        "",
    ));
    out.push("#[derive(Clone, Copy, Debug, PartialEq)]".to_string());
    out.push(format!("pub struct {} {{", schema.iface));
    out.push("    /// Stable authoring name.".to_string());
    out.push("    pub id: &'static str,".to_string());
    out.push("    /// Numeric id stored in cells and in the lock file. Never shifts.".to_string());
    out.push("    pub code: u16,".to_string());
    let mut emitted: Vec<&str> = Vec::new();
    for (key, field) in &schema.fields {
        match key.find('.') {
            None => {
                out.extend(doc(field.doc.as_ref(), "    "));
                let t = rust_type(&schema.iface_prefix, key, field)?;
                let t = if is_optional(field) {
                    format!("Option<{t}>")
                } else {
                    t
                };
                out.push(format!("    pub {}: {t},", names::snake(key)));
            }
            Some(i) => {
                let g = &key[..i];
                if emitted.contains(&g) {
                    continue;
                }
                emitted.push(g);
                out.push(format!(
                    "    pub {}: Option<{}{}>,",
                    names::snake(g),
                    schema.iface_prefix,
                    names::pascal(g)
                ));
            }
        }
    }
    out.push("}".to_string());
    out.push(String::new());

    // --- registry ------------------------------------------------------------
    out.push("/// Authoring ids, index == code.".to_string());
    out.push(format!("pub static {p}_IDS: [&str; {count}] = ["));
    out.push(wrap(
        &defs
            .iter()
            .map(|d| str_lit(d.str_of("id")))
            .collect::<Vec<_>>(),
        "    ",
    ));
    out.push("];".to_string());
    out.push(String::new());

    out.push("/// Every def, index == code, tombstones included.".to_string());
    out.push(format!(
        "pub static {}S: [{}; {count}] = [",
        p, schema.iface
    ));
    for d in defs {
        out.push(format!("    {},", def_literal(d, schema)?));
    }
    out.push("];".to_string());
    out.push(String::new());

    out.push(format!("pub const {p}_COUNT: usize = {count};"));
    out.push(String::new());

    let idmod = names::snake(&schema.prefix.to_ascii_lowercase());
    out.push(format!(
        "/// id -> code. Consts, so `{idmod}::STONE` is a compile-time constant."
    ));
    out.push(format!("pub mod {idmod} {{"));
    let mut const_names: Vec<String> = Vec::new();
    for d in defs {
        let id = d.str_of("id");
        let n = names::screaming_snake(id);
        if const_names.contains(&n) {
            bail!(
                "two {} ids collapse to the Rust constant '{n}'",
                schema.kind
            );
        }
        const_names.push(n.clone());
        out.push(format!(
            "    pub const {n}: u16 = {};",
            d.num("code") as u64
        ));
    }
    out.push("}".to_string());
    out.push(String::new());

    out.push("/// Sentinel for \"this threshold can never be reached\".".to_string());
    out.push("pub const NEVER: u16 = 0xffff;".to_string());
    out.push(String::new());

    // --- bit constants -------------------------------------------------------
    for set in &schema.constants {
        out.push("bitflags::bitflags! {".to_string());
        out.extend(doc(set.doc.as_ref(), "    "));
        out.push("    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]".to_string());
        out.push(format!(
            "    pub struct {}: u32 {{",
            names::pascal(&set.name)
        ));
        for (i, v) in set.values.iter().enumerate() {
            out.push(format!(
                "        const {} = 1 << {i};",
                names::screaming_snake(v)
            ));
        }
        out.push("    }".to_string());
        out.push("}".to_string());
        out.push(String::new());
    }

    // --- flat tables ---------------------------------------------------------
    out.push("// Flat tables, index == code. Built by the compiler, not at startup:".to_string());
    out.push("// the sim, renderer and collision read these in per-cell loops, and an".to_string());
    out.push("// array read is far cheaper than a map hit plus a struct deref.".to_string());
    out.push(String::new());
    for t in schema.hot_arrays() {
        let mut values = Vec::with_capacity(count);
        for (code, d) in defs.iter().enumerate() {
            let v = (t.value)(d, tctx).unwrap_or(t.fill);
            values.push(table_lit(t.array, v, &t.name, code)?);
        }
        // A callback cannot return an error through `Option<f64>`, so a bad
        // `bit()` lookup is stashed and surfaces here, naming the table.
        if let Some(e) = tctx.take_error() {
            return Err(err!("{}: {}", t.name, e.message));
        }
        out.extend(doc(t.doc.as_ref(), ""));
        out.push(format!(
            "pub static {}: [{}; {count}] = [",
            t.name,
            t.array.rust_elem()
        ));
        out.push(wrap(&values, "    "));
        out.push("];".to_string());
        out.push(String::new());
    }

    // --- pair matrices -------------------------------------------------------
    //
    // One bit per pair, packed. The TS build base64'd this and inflated it at
    // module init to keep the bundle small; a Rust static array costs nothing at
    // runtime, so the accessor reads the packed bytes directly.
    for m in &schema.matrices {
        let n = count * count;
        let mut packed = vec![0u8; n.div_ceil(8)];
        for d in defs {
            let Some(row) = (m.row)(d, tctx) else {
                continue;
            };
            for target in row {
                let i = d.num("code") as usize * count + tctx.code(&target) as usize;
                packed[i >> 3] |= 1 << (i & 7);
            }
        }
        let fname = names::snake(&m.name);
        out.extend(doc(m.doc.as_ref(), ""));
        out.push(format!(
            "pub static {}_BITS: [u8; {}] = [",
            m.name,
            packed.len()
        ));
        out.push(wrap(
            &packed.iter().map(|b| b.to_string()).collect::<Vec<_>>(),
            "    ",
        ));
        out.push("];".to_string());
        out.push(String::new());
        out.push(format!(
            "/// `true` when the `{}` pair matrix has the (a, b) bit set.",
            m.name
        ));
        out.push("#[inline]".to_string());
        out.push(format!("pub fn {fname}(a: u16, b: u16) -> bool {{"));
        out.push(format!("    let i = a as usize * {count} + b as usize;"));
        out.push(format!(
            "    i < {n} && ({}_BITS[i >> 3] >> (i & 7)) & 1 != 0",
            m.name
        ));
        out.push("}".to_string());
        out.push(String::new());
    }

    // --- reflection registries -----------------------------------------------
    //
    // Rust cannot look a static up by name, and two consumers need to: the
    // parity test that diffs these tables against the TypeScript build, and the
    // tuning index. Emitting the registry is cheaper than either of them
    // restating 79 table names by hand and drifting.
    out.push(
        "/// Every flat table in this module, by name. For the gates, not the game.".to_string(),
    );
    out.push(format!(
        "pub static {p}_TABLES: &[(&str, crate::Table)] = &["
    ));
    for t in schema.hot_arrays() {
        let variant = match t.array {
            ArrayKind::U8 => "U8",
            ArrayKind::U16 => "U16",
            ArrayKind::U32 => "U32",
            ArrayKind::F32 => "F32",
        };
        out.push(format!(
            "    (\"{}\", crate::Table::{variant}(&{})),",
            t.name, t.name
        ));
    }
    out.push("];".to_string());
    out.push(String::new());

    out.push("/// Authoring id -> code, by name. For the gates, not the game.".to_string());
    out.push(format!("pub static {p}_CODES: &[(&str, u16)] = &["));
    for d in defs {
        out.push(format!(
            "    (\"{}\", {}),",
            d.str_of("id"),
            d.num("code") as u64
        ));
    }
    out.push("];".to_string());
    out.push(String::new());

    if !schema.matrices.is_empty() {
        out.push(
            "/// Every pair matrix in this module: name, side length, packed bits.".to_string(),
        );
        out.push(format!(
            "pub static {p}_MATRICES: &[(&str, usize, &[u8])] = &["
        ));
        for m in &schema.matrices {
            out.push(format!("    (\"{}\", {count}, &{}_BITS),", m.name, m.name));
        }
        out.push("];".to_string());
        out.push(String::new());
    }

    let joined = out.join("\n");
    let mut text = collapse_blank_runs(&joined);
    while text.ends_with('\n') {
        text.pop();
    }
    text.push('\n');
    Ok(text)
}

/// `/\n{3,}/g -> "\n\n"` — three or more newlines collapse to one blank line.
fn collapse_blank_runs(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut run = 0usize;
    for c in s.chars() {
        if c == '\n' {
            run += 1;
            if run <= 2 {
                out.push(c);
            }
            continue;
        }
        run = 0;
        out.push(c);
    }
    out
}

/// One def as a struct literal, fields in schema order, defaults included.
fn def_literal(d: &Def, schema: &Schema) -> Result<String> {
    let mut parts: Vec<String> = vec![
        format!("id: {}", str_lit(d.str_of("id"))),
        format!("code: {}", d.num("code") as u64),
    ];
    let mut emitted: Vec<String> = vec!["id".into(), "code".into()];

    for (key, field) in &schema.fields {
        let name = match key.find('.') {
            None => key.clone(),
            Some(i) => key[..i].to_string(),
        };
        if emitted.contains(&name) {
            continue;
        }
        emitted.push(name.clone());

        if name != *key {
            // A group: emit the whole nested struct, or None.
            let group_fields: Vec<(&str, &Field)> = schema
                .fields
                .iter()
                .filter(|(k, _)| k.starts_with(&format!("{name}.")))
                .map(|(k, f)| (&k[name.len() + 1..], f))
                .collect();
            let lit = match d.get(&name) {
                Some(Value::Group(g)) => {
                    let mut inner = Vec::with_capacity(group_fields.len());
                    for (leaf, sf) in &group_fields {
                        let snode = parse_type(&sf.ty)?;
                        let l = match g.get(leaf) {
                            Some(v) => {
                                let raw = value_lit(&snode, sf, &schema.iface_prefix, leaf, v)?;
                                if sf.required {
                                    raw
                                } else {
                                    format!("Some({raw})")
                                }
                            }
                            None if !sf.required => "None".to_string(),
                            None => bail!(
                                "{} '{}' group '{name}' is missing required '{leaf}'",
                                schema.kind,
                                d.str_of("id")
                            ),
                        };
                        inner.push(format!("{}: {l}", names::snake(leaf)));
                    }
                    format!(
                        "Some({}{} {{ {} }})",
                        schema.iface_prefix,
                        names::pascal(&name),
                        inner.join(", ")
                    )
                }
                _ => "None".to_string(),
            };
            parts.push(format!("{}: {lit}", names::snake(&name)));
            continue;
        }

        let node = parse_type(&field.ty)?;
        let lit = match d.get(&name) {
            Some(v) => {
                let raw = value_lit(&node, field, &schema.iface_prefix, &name, v)?;
                if is_optional(field) {
                    format!("Some({raw})")
                } else {
                    raw
                }
            }
            None if is_optional(field) => "None".to_string(),
            None => bail!(
                "{} '{}' is missing '{name}', which is neither optional nor defaulted",
                schema.kind,
                d.str_of("id")
            ),
        };
        parts.push(format!("{}: {lit}", names::snake(&name)));
    }

    Ok(format!("{} {{ {} }}", schema.iface, parts.join(", ")))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lock_with(kind: &str, entries: &[(&str, u32)]) -> Lock {
        let mut l = Lock::default();
        l.set_kind(
            kind,
            entries.iter().map(|(a, b)| (a.to_string(), *b)).collect(),
        );
        l
    }

    fn ids(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn a_locked_id_keeps_its_code_forever() {
        let lock = lock_with("block", &[("air", 0), ("stone", 1), ("dirt", 2)]);
        let a = assign_codes("block", &ids(&["dirt", "stone", "air"]), &lock);
        assert_eq!(a.codes["air"], 0);
        assert_eq!(a.codes["stone"], 1);
        assert_eq!(a.codes["dirt"], 2);
        assert!(a.tombstones.is_empty());
    }

    #[test]
    fn a_removed_id_leaves_its_code_reserved() {
        let lock = lock_with("block", &[("air", 0), ("mud", 1), ("dirt", 2)]);
        // `mud` is gone from content; `sand` is new and must NOT take code 1.
        let a = assign_codes("block", &ids(&["air", "dirt", "sand"]), &lock);
        assert_eq!(a.tombstones, vec!["mud".to_string()]);
        assert_eq!(a.codes["sand"], 3);
        // The tombstone still occupies its slot in the next lock.
        assert!(a.next_lock.contains(&("mud".to_string(), 1)));
    }

    #[test]
    fn new_ids_take_the_lowest_free_slot_in_source_order() {
        let lock = Lock::default();
        let a = assign_codes("block", &ids(&["air", "stone", "dirt"]), &lock);
        assert_eq!(a.codes["air"], 0);
        assert_eq!(a.codes["stone"], 1);
        assert_eq!(a.codes["dirt"], 2);
    }

    #[test]
    fn assignment_is_idempotent() {
        let lock = Lock::default();
        let first = assign_kind_codes("block", &ids(&["air", "stone"]), &lock);
        let mut l2 = Lock::default();
        l2.set_kind("block", first.clone());
        let second = assign_kind_codes("block", &ids(&["air", "stone"]), &l2);
        assert_eq!(first, second);
    }

    #[test]
    fn integer_tables_reject_a_value_that_would_not_survive_the_store() {
        assert!(table_lit(ArrayKind::U8, 300.0, "MAT_X", 3).is_err());
        assert!(table_lit(ArrayKind::U8, -1.0, "MAT_X", 3).is_err());
        assert!(table_lit(ArrayKind::U8, 1.5, "MAT_X", 3).is_err());
        assert_eq!(
            table_lit(ArrayKind::U16, 65535.0, "MAT_X", 0).unwrap(),
            "65535"
        );
        assert_eq!(
            table_lit(ArrayKind::F32, f64::INFINITY, "MAT_X", 0).unwrap(),
            "f32::INFINITY"
        );
    }
}
