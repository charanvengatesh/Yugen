//! Code generation: content records -> `godgame-data/src/<kind>.rs`.
//!
//! Three jobs, in order:
//!  1. assign stable numeric codes through `content/ids.lock.json` (FORMAT.md §4);
//!  2. validate every record against the schema, now that the id set is known,
//!     so `ref(block)` can be checked at compile time;
//!  3. print a deterministic Rust module (FORMAT.md §5) — sorted by code, no
//!     timestamps, no hash-map iteration order — so a rebuild that changed
//!     nothing produces a byte-identical file and `--check` means something.
//!
//! The output depends only on `bitflags`, so it can be linked by the sim, the
//! renderer, the benches and the xtask gates without dragging anything with it.
//!
//! Where the TS emitter wrote TypeScript, this writes Rust, and three things get
//! better in the translation: a string-union `enum` becomes a real `enum`, a
//! const-object bit set becomes `bitflags!`, and a base64 pair matrix becomes a
//! packed byte array with an inline accessor — no runtime inflation at all.

use crate::error::Result;
use crate::lock::{KindLock, Lock};
use crate::names;
use crate::parser::{FieldMap, RawRecord, RawValue};
use crate::schema::{ArrayKind, Field, Schema, TableCtx, TypeNode, parse_type};
use crate::value::{Def, Value};
use crate::{bail, err};
use std::collections::{HashMap, HashSet};
use std::rc::Rc;

pub struct EmitResult {
    /// The generated Rust module source.
    pub source: String,
    /// The lock as it should be on disk after this compile.
    pub lock: Lock,
    pub warnings: Vec<String>,
    pub count: usize,
    pub tombstones: Vec<String>,
}

const GEN_HEADER: &str = "// GENERATED by contentc — DO NOT EDIT";

// ---------------------------------------------------------------------------
// Code assignment
// ---------------------------------------------------------------------------

struct Assignment {
    codes: HashMap<String, u32>,
    next_lock: KindLock,
    tombstones: Vec<String>,
}

/// Give every id a code: locked ids keep theirs forever, new ids take the lowest
/// free slot, and locked ids that vanished from `content/` stay reserved as
/// tombstones. This is the invariant that lets a saved chunk survive a content
/// edit, so it is deliberately the least clever code in the compiler.
fn assign_codes(kind: &str, ids: &[String], lock: &Lock) -> Assignment {
    let prior = lock.kind(kind);
    let mut codes: HashMap<String, u32> = HashMap::new();
    let mut used: HashSet<u32> = HashSet::new();

    for id in ids {
        if let Some((_, c)) = prior.iter().find(|(k, _)| k == id) {
            codes.insert(id.clone(), *c);
            used.insert(*c);
        }
    }
    for (id, c) in prior {
        if !codes.contains_key(id) {
            used.insert(*c); // tombstone: the code stays reserved
        }
    }

    let mut next = 0u32;
    for id in ids {
        if codes.contains_key(id) {
            continue;
        }
        while used.contains(&next) {
            next += 1;
        }
        codes.insert(id.clone(), next);
        used.insert(next);
    }

    let mut tombstones: Vec<String> = prior
        .iter()
        .filter(|(id, _)| !codes.contains_key(id))
        .map(|(id, _)| id.clone())
        .collect();
    tombstones.sort();

    let mut next_lock: KindLock = codes.iter().map(|(id, c)| (id.clone(), *c)).collect();
    for t in &tombstones {
        let c = prior
            .iter()
            .find(|(k, _)| k == t)
            .map(|(_, c)| *c)
            .unwrap_or(0);
        next_lock.push((t.clone(), c));
    }
    // Sort by code, then id, so two ids can never swap places between runs.
    next_lock.sort_by(|a, b| a.1.cmp(&b.1).then_with(|| a.0.cmp(&b.0)));

    Assignment {
        codes,
        next_lock,
        tombstones,
    }
}

/// Assign one kind's codes without compiling it, so the driver can build a lock
/// covering EVERY kind before any kind emits a table. That is what makes
/// `TableCtx::foreign_code` well-defined in both directions: an item table can
/// ask for a block code and a block table for an item code, with no compile
/// order that satisfies one at the other's expense.
///
/// Idempotent, and it is the same function `compile` runs, so the codes it hands
/// out here are exactly the ones the real compile will use.
pub fn assign_kind_codes(kind: &str, ids: &[String], lock: &Lock) -> KindLock {
    let mut unique: Vec<String> = Vec::new();
    let mut seen: HashSet<&str> = HashSet::new();
    for id in ids {
        if seen.insert(id.as_str()) {
            unique.push(id.clone());
        }
    }
    assign_codes(kind, &unique, lock).next_lock
}

// ---------------------------------------------------------------------------
// Compile
// ---------------------------------------------------------------------------

/// Ids of every kind, so a `ref(item)` inside a `.block` can be checked at
/// compile time. Collected by a parse-only pre-pass in the driver, because kinds
/// reference each other in both directions (a block drops an item; an item
/// places a block) and no single compile order can satisfy that.
pub type Foreign = HashMap<String, HashSet<String>>;

pub fn compile(
    schema: &Schema,
    records: &[RawRecord],
    lock: &Lock,
    sources: &[String],
    foreign: &Foreign,
) -> Result<EmitResult> {
    let mut seen: Vec<(String, &RawRecord)> = Vec::new();
    for rec in records {
        if rec.kind != schema.kind {
            bail!(&rec.loc, "expected @{}, got @{}", schema.kind, rec.kind);
        }
        if let Some((_, dup)) = seen.iter().find(|(id, _)| *id == rec.id) {
            bail!(
                &rec.loc,
                "duplicate {} '{}' (also at {})",
                schema.kind,
                rec.id,
                dup.loc
            );
        }
        seen.push((rec.id.clone(), rec));
    }

    let ids: Vec<String> = seen.iter().map(|(id, _)| id.clone()).collect();
    let Assignment {
        mut codes,
        next_lock,
        tombstones,
    } = assign_codes(&schema.kind, &ids, lock);
    for t in &tombstones {
        let c = next_lock
            .iter()
            .find(|(k, _)| k == t)
            .map(|(_, c)| *c)
            .unwrap_or(0);
        codes.insert(t.clone(), c);
    }

    // The schema's own kind resolves against the ids it is compiling; every
    // other kind against the pre-pass registry.
    let mut registries: Foreign = foreign.clone();
    registries.insert(schema.kind.clone(), codes.keys().cloned().collect());
    let ctx = crate::schema::ResolveCtx::new(&registries);

    // A kind with no content yet is legal (the directory is added before the
    // records are), and must not take the max of an empty list.
    let count = codes.values().copied().max().map_or(0, |m| m as usize + 1);
    let mut defs: Vec<Option<Def>> = vec![None; count];

    for (id, rec) in &seen {
        let mut def = crate::schema::resolve_record(schema, rec, &ctx)?;
        let code = codes[id];
        def.insert("code", Value::Int(code as i64));
        defs[code as usize] = Some(def);
    }
    for (c, slot) in defs.iter_mut().enumerate() {
        if slot.is_some() {
            continue;
        }
        let id = tombstones
            .iter()
            .find(|t| {
                next_lock
                    .iter()
                    .any(|(k, code)| k == *t && *code as usize == c)
            })
            .cloned()
            .unwrap_or_else(|| format!("_reserved{c}"));
        let rec = tombstone_record(schema, &id);
        let mut def = crate::schema::resolve_record(schema, &rec, &ctx)?;
        def.insert("code", Value::Int(c as i64));
        *slot = Some(def);
    }
    let defs: Vec<Def> = defs.into_iter().map(Option::unwrap).collect();

    let mut bits: HashMap<String, HashMap<String, u32>> = HashMap::new();
    for set in &schema.constants {
        if set.values.len() > 32 {
            bail!("{} exceeds 32 bits", set.name);
        }
        bits.insert(
            set.name.clone(),
            set.values
                .iter()
                .enumerate()
                .map(|(i, v)| (v.clone(), i as u32))
                .collect(),
        );
    }

    // Reads the lock rather than a compiled registry, which is what makes this
    // order-free: the driver has already assigned every kind's codes into the
    // lock, so a table can reach any kind regardless of which compiles first.
    let mut foreign_codes: HashMap<String, HashMap<String, u32>> = HashMap::new();
    for kind in foreign.keys() {
        foreign_codes.insert(
            kind.clone(),
            lock.kind(kind).iter().cloned().collect::<HashMap<_, _>>(),
        );
    }
    let tctx = TableCtx::new(&codes, &foreign_codes, &bits);

    let source = print(schema, &defs, count, &tctx, sources, &tombstones)?;
    if let Some(e) = tctx.take_error() {
        return Err(e);
    }

    let mut out_lock = lock.clone();
    out_lock.set_kind(&schema.kind, next_lock);

    Ok(EmitResult {
        source,
        lock: out_lock,
        warnings: ctx.into_warnings(),
        count,
        tombstones,
    })
}

fn tombstone_record(schema: &Schema, id: &str) -> RawRecord {
    let loc = crate::error::Loc {
        file: Rc::from("<tombstone>"),
        line: 0,
    };
    let mut fields = FieldMap::default();
    for (k, v) in &schema.tombstone {
        let text = if v.starts_with('"') && v.ends_with('"') && v.len() >= 2 {
            v[1..v.len() - 1].to_string()
        } else {
            v.clone()
        };
        fields.push(
            k,
            RawValue {
                text: Some(text),
                lines: None,
                loc: loc.clone(),
            },
        );
    }
    RawRecord {
        kind: schema.kind.clone(),
        id: id.to_string(),
        loc,
        fields,
    }
}

