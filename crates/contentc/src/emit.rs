// ---------------------------------------------------------------------------

/// Field name paired with its descriptor, borrowed from the schema.
type FieldRef<'a> = (&'a str, &'a Field);
/// A dotted group: its name and its leaf fields, in declaration order.
type GroupRef<'a> = (&'a str, Vec<FieldRef<'a>>);

/// Split a schema's dotted fields into top-level fields and named groups.
fn partition(schema: &Schema) -> (Vec<FieldRef<'_>>, Vec<GroupRef<'_>>) {
    let mut flat: Vec<(&str, &Field)> = Vec::new();
    let mut groups: Vec<(&str, Vec<(&str, &Field)>)> = Vec::new();
    for (key, field) in &schema.fields {
        match key.find('.') {
            None => flat.push((key.as_str(), field)),
            Some(i) => {
                let g = &key[..i];
                let leaf = &key[i + 1..];
                match groups.iter_mut().find(|(name, _)| *name == g) {
                    Some((_, v)) => v.push((leaf, field)),
                    None => groups.push((g, vec![(leaf, field)])),
                }
            }
        }
    }
    (flat, groups)
}

/// The name of the Rust enum a non-mapped `enum(...)` field becomes.
///
/// `scope` is the struct the field belongs to — the schema's `iface_prefix` for
/// a top-level or group field, the element name for a `record[]` sub-field — so
/// two unrelated `mode` fields cannot collide.
fn enum_name(scope: &str, key: &str, field: &Field) -> String {
    match &field.alias {
        Some(a) => a.clone(),
        None => format!("{scope}{}", names::pascal(key)),
    }
}

/// The integer type a `map`ped enum resolves to.
fn mapped_int_type(field: &Field) -> &'static str {
    let fits = field
        .map
        .as_ref()
        .is_some_and(|m| m.iter().all(|(_, v)| (0..=255).contains(v)));
    if fits { "u8" } else { "i32" }
}

fn rust_type(scope: &str, key: &str, field: &Field) -> Result<String> {
    if field.map.is_some() {
        return Ok(mapped_int_type(field).to_string());
    }
    rust_type_of(&parse_type(&field.ty)?, scope, key, field)
}

fn rust_type_of(node: &TypeNode, scope: &str, key: &str, field: &Field) -> Result<String> {
    Ok(match node {
        TypeNode::Int => "i32".into(),
        TypeNode::Float | TypeNode::Chance => "f32".into(),
        TypeNode::Bool => "bool".into(),
        TypeNode::Str | TypeNode::Ref { .. } => "&'static str".into(),
        TypeNode::Enum(_) => enum_name(scope, key, field),
        TypeNode::Color => "[u8; 3]".into(),
        TypeNode::Range => "[f32; 2]".into(),
        TypeNode::Text => "&'static [&'static str]".into(),
        TypeNode::List(of) => {
            format!("&'static [{}]", rust_type_of(of, scope, key, field)?)
        }
        TypeNode::Record => {
            let elem = field
                .element
                .clone()
                .ok_or_else(|| err!("'{key}' is record[] but names no element struct"))?;
            format!("&'static [{elem}]")
        }
    })
}

/// A field is `Option<T>` when nothing guarantees it a value.
fn is_optional(field: &Field) -> bool {
    !(field.required || field.default.is_some())
}

